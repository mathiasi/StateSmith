#nullable enable

using StateSmith.Input.Expansions;
using StateSmith.Output.UserConfig;
using StateSmith.Runner;
using StateSmithTest.Processes;
using System;
using Xunit;

namespace StateSmithTest.Output.Rust;

/// <summary>
/// Rust spike: generates `test-misc/rust-light/src/light_sm.rs` from `test-misc/rust-light/LightSm.plantuml`.
/// Run with: dotnet test --filter "FullyQualifiedName~RustLightSmGenTests"
/// </summary>
public class RustLightSmGenTests
{
    public static string CrateDirectory => AppDomain.CurrentDomain.BaseDirectory + "../../../../test-misc/rust-light/";

    [Fact]
    public void GenerateLightSm()
    {
        RunnerSettings settings = new(diagramFile: CrateDirectory + "LightSm.plantuml", outputDirectory: CrateDirectory + "src/", transpilerId: TranspilerId.Rust);
        settings.outputStateSmithVersionInfo = false; // keep diffs quiet
        settings.propagateExceptions = true;
        settings.dumpGilCodeOnError = true;
        settings.outputGilCodeAlways = true; // handy while developing the transpiler
        settings.style = new RustfmtLikeStyle(); // K&R braces like rustfmt. The transpiler also handles the default (braces on new lines).

        SmRunner runner = new(settings, new LightSmRenderConfig());
        runner.Run();
    }

    /// <summary>
    /// Builds and runs the example crate if cargo is installed.
    /// </summary>
    [Fact]
    public void CargoRun()
    {
        GenerateLightSm();

        SimpleProcess process = new()
        {
            WorkingDirectory = CrateDirectory,
            ProgramPath = "cargo",
            Args = "run --quiet"
        };
        process.Run(timeoutMs: SimpleProcess.DefaultLongTimeoutMs);
    }

    public class RustfmtLikeStyle : StateSmith.Output.CodeStyleSettings
    {
        public override bool BracesOnNewLines => false;
    }

    public class LightSmRenderConfig : IRenderConfigRust
    {
        string IRenderConfig.FileTop => """
            // Generated by StateSmith (Rust spike). Do not edit.
            """;

        string IRenderConfigRust.Imports => """
            use crate::light::Light;
            """;

        // `name: Type = const_initializer,` lets the generator emit both the struct field and a `const fn new()`.
        string IRenderConfig.VariableDeclarations => """
            count: u8 = 0,
            light: Light = Light::new(),
            group_exits: u16 = 0,
            """;

        public class Expansions : UserExpansionScriptBase
        {
#pragma warning disable IDE1006 // Naming Styles
            public string count => AutoVarName();
            // owned field: the light driver lives inside the state machine's vars
            public string light_off() => $"{VarsPath}light.off()";
            public string light_blue() => $"{VarsPath}light.blue()";
            public string light_yellow() => $"{VarsPath}light.yellow()";
            // user impl block: implemented in `light.rs` as `impl LightSm { fn record_group_exit(&mut self) }`
            public string record_group_exit() => "self.record_group_exit()";
#pragma warning restore IDE1006 // Naming Styles
        }
    }
}
